"""Append-only decision log, one file per decision (no shared file, so merges of new decisions never conflict).

    python scripts/decision_log.py add --title T --question Q --answer A [--why W] [--said-in WHERE]
                                       [--supersedes ID] [--dir docs/decisions]
    python scripts/decision_log.py index [--dir docs/decisions] [--out FILE]   # print the index (generated)
    python scripts/decision_log.py check [--dir docs/decisions]                # ids match files, supersedes exist

Ids are D-<timestamp UTC>-<slug>; two adds in the same second with the same title get -2, -3 ... suffixes. A file is
created with exclusive mode and never rewritten; to change a decision, add a new one with `--supersedes <id>`.
`index` prints to stdout by default: do not commit a generated INDEX.md (it is one shared file and two branches would
conflict on it). `--said-in` records where the owner said it (session date, PR comment link). An entry is written by
an agent and is NOT proof that the owner said it; see docs/LIMITS.md.
"""
import argparse
import datetime
import os
import re
import sys


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40] or "decision"


def one_line(name, v):
    if v is not None and re.search(r"[\r\n\x00-\x08\x0b\x0c\x0e-\x1f]", v):
        raise ValueError(f"--{name} must be one line without control characters")
    return v


def add(a):
    for k in ("title", "supersedes", "said_in"):
        one_line(k.replace("_", "-"), getattr(a, k))
    os.makedirs(a.dir, exist_ok=True)
    now = datetime.datetime.now(datetime.timezone.utc)
    stem = f"D-{now:%Y%m%dT%H%M%S}-{slug(a.title)}"
    for n in range(1, 1000):
        did = stem if n == 1 else f"{stem}-{n}"
        path = os.path.join(a.dir, did + ".md")
        body = (f"---\nid: {did}\ndate: {now:%Y-%m-%d}\nstatus: decided\nsupersedes: {a.supersedes or ''}\n"
                f"said-in: {a.said_in or ''}\n---\n"
                f"# {a.title}\n\n**Question:** {a.question}\n\n**Answer (owner's words):** {a.answer}\n\n"
                f"**Why / consequence:** {a.why or '-'}\n")
        try:
            with open(path, "x", encoding="utf-8") as f:  # 'x' = fail if it exists: append-only
                f.write(body)
        except FileExistsError:
            continue
        print(path)
        return 0
    sys.stderr.write("could not find a free id\n")
    return 2


def entries(d):
    for n in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if n.startswith("D-") and n.endswith(".md"):
            with open(os.path.join(d, n), encoding="utf-8") as f:
                yield n, f.read()


def index(a):
    rows = []
    for n, t in entries(a.dir):
        m = re.search(r"^# (.+)$", t, re.M)
        rows.append(f"| {n[:-3]} | {m.group(1) if m else ''} |")
    text = ("<!-- GENERATED by scripts/decision_log.py index; do not edit, do not commit -->\n| id | title |\n|---|---|\n"
            + "\n".join(rows) + "\n")
    if a.out:
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


def check(a):
    bad = 0
    items = list(entries(a.dir))
    ids = {n[:-3] for n, _ in items}
    for n, t in items:
        m = re.search(r"^id: (\S+)$", t, re.M)
        if not m or m.group(1) + ".md" != n:
            print(f"BAD id in {n}"); bad = 1
        s = re.search(r"^supersedes: (\S+)$", t, re.M)
        if s and s.group(1) not in ids:
            print(f"BAD supersedes in {n}: {s.group(1)} not found"); bad = 1
    return bad


def main(argv):
    p = argparse.ArgumentParser()
    sp = p.add_subparsers(dest="cmd", required=True)
    for name in ("add", "index", "check"):
        s = sp.add_parser(name)
        s.add_argument("--dir", default="docs/decisions")
        if name == "add":
            s.add_argument("--title", required=True); s.add_argument("--question", required=True)
            s.add_argument("--answer", required=True); s.add_argument("--why"); s.add_argument("--supersedes")
            s.add_argument("--said-in", dest="said_in")
        if name == "index":
            s.add_argument("--out")
    a = p.parse_args(argv)
    try:
        return {"add": add, "index": index, "check": check}[a.cmd](a)
    except ValueError as e:
        sys.stderr.write(f"refused: {e}\n")
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
